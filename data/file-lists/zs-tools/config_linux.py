def _get_network_config_service():
    if shell.run('which pgrep'):
        if shell.run('pgrep -f NetworkManager'):
            logger.debug("Detected NetworkManager service")
            return 'NetworkManager'
        elif shell.run('pgrep -f systemd-networkd'):
            logger.debug("Detected systemd-networkd service")
            return 'networkd'
    else:
        if shell.run('ps -C NetworkManager | grep NetworkManager'):
            logger.debug("Detected NetworkManager service (via ps)")
            return 'NetworkManager'
        elif shell.run('ps -C systemd-networkd | grep systemd-network'):
            logger.debug("Detected systemd-networkd service (via ps)")
            return 'networkd'
    logger.debug("No network management service detected")
    return None


def _get_network_config_persist_style(os_id, os_version_id):
    major_version = None
    if os_version_id is not None:
        match = re.match(r'(\d+)', str(os_version_id))
        if match:
            try:
                major_version = int(match.group(1))
            except ValueError:
                major_version = None
    if os_id in ['centos', 'rhel', 'rocky', 'almalinux', 'ol'] and \
            major_version is not None and major_version >= 10 and \
            os.path.exists(NetworkManagerKeyfilePersistOperator.config_file_style):
        logger.debug("Using NetworkManager keyfile style")
        return NetworkManagerKeyfilePersistOperator.config_file_style
    if os_id == 'fedora' and major_version is not None and major_version >= 42 and \
            os.path.exists(NetworkManagerKeyfilePersistOperator.config_file_style):
        logger.debug("Using NetworkManager keyfile style (Fedora)")
        return NetworkManagerKeyfilePersistOperator.config_file_style
    if os_id == 'amzn' and os.path.exists(SystemdNetworkdConfigPersistOperator.config_file_style):
        return SystemdNetworkdConfigPersistOperator.config_file_style
    if os.path.exists(FedoraNetworkConfigPersistOperator.config_file_style):
        return FedoraNetworkConfigPersistOperator.config_file_style
    if os.path.exists(SuseNetworkConfigPersistOperator.config_file_style):
        return SuseNetworkConfigPersistOperator.config_file_style
    elif os.path.exists(DebianNetworkConfigPersistOperator.config_file_style):
        return DebianNetworkConfigPersistOperator.config_file_style
    else:
        raise ConfigException('not supported os: {0} {1}'.format(os_id, os_version_id))


