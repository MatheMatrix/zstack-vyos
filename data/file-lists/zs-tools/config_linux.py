def _get_os_info():
    with open('/etc/os-release') as f:
        content = f.read()
        lines = content.split('\n')
        os_id = None
        os_version_id = None
        for line in lines:
            match_ret = re.match('^[\s\t]*id=(.*)', line, re.IGNORECASE)
            if match_ret:
                os_id = match_ret.group(1).replace('"', '')
            match_ret = re.match('^[\s\t]*version_id=(.*)', line, re.IGNORECASE)
            if match_ret:
                os_version_id = match_ret.group(1).replace('"', '')
                os_version_id = os_version_id.split('.')[0]
        return os_id, os_version_id


def _get_all_interfaces_by_mac():
    """
    Get all network interfaces grouped by MAC address.
    Returns: {mac: [nic_name1, nic_name2, ...]}
    """
    all_interfaces = {}
    try:
        ret = _call_if_err_raise('ls /sys/class/net/')
        if not ret:
            return {}

        for nic_name in [n.strip() for n in ret.split('\n') if n.strip()]:
            mac_file = '/sys/class/net/{0}/address'.format(nic_name)
            if not os.path.exists(mac_file):
                continue

            try:
                with open(mac_file, 'r') as f:
                    mac = f.read().strip()
                if mac and ':' in mac:
                    if mac not in all_interfaces:
                        all_interfaces[mac] = []
                    all_interfaces[mac].append(nic_name)
            except:
                continue
    except Exception:
        pass

    return all_interfaces


def _find_nic_by_mac(mac, is_bond=False):
    """
    Find network interface by MAC address.
    For bond devices, returns the bond master interface.
    For normal devices, returns the physical interface.
    """
    all_interfaces = _get_all_interfaces_by_mac()

    if mac not in all_interfaces:
        return None

    candidates = all_interfaces[mac]

    if is_bond:
        # Find bond master device
        for nic_name in candidates:
            bonding_dir = '/sys/class/net/{0}/bonding'.format(nic_name)
            master_file = '/sys/class/net/{0}/master'.format(nic_name)
            # Bond master has bonding/ dir and no master file
            if os.path.exists(bonding_dir) and not os.path.exists(master_file):
                logger.debug('Found bond master {0} for MAC {1}'.format(nic_name, mac))
                return nic_name
    else:
        # Find physical device (has PCI device and not a slave)
        for nic_name in candidates:
            device_link = '/sys/class/net/{0}/device'.format(nic_name)
            master_file = '/sys/class/net/{0}/master'.format(nic_name)
            if os.path.exists(device_link) and not os.path.exists(master_file):
                logger.debug('Found physical interface {0} for MAC {1}'.format(nic_name, mac))
                return nic_name

    # Fallback: return first candidate
    if candidates:
        logger.warning('No specific match for MAC {0}, using {1}'.format(mac, candidates[0]))
        return candidates[0]

    return None


def _get_phy_interfaces():
    ret = _call_if_err_raise('ls -l /sys/class/net/*/device')
    if not ret:
        return None
    '''
    the format of "ret" like this:
    lrwxrwxrwx 1 root root 0 Nov 21 18:04 /sys/class/net/enp101s0f0/device -> ../../../0000:65:00.0
    '''
    phy_interfaces = [line.split('/')[4] for line in ret.split('\n') if len(line.split('/')) > 5]
    path_list = ['/sys/class/net/%s/address' % interface for interface in phy_interfaces]
    ret = _call_if_err_raise('cat ' + ' '.join(path_list))
    if not ret:
        return None

    mac_list = [mac for mac in ret.split('\n') if ':' in mac]
    if len(phy_interfaces) != len(mac_list):
        raise ConfigException(
            'get vm physical interface failed, nic names:{0}, nic macs:{1}'.format(phy_interfaces, mac_list))

    return dict(zip(mac_list, phy_interfaces))


def _set_nic_name_for_config(nics):
    def update_nic_names():
        for nic in nics:
            mac = nic.get('mac')
            if not mac:
                logger.error('NIC configuration missing MAC address')
                return False

            # Check if this is a bond device
            is_bond = _is_bond_nic(nic)

            nic_name = _find_nic_by_mac(mac, is_bond=is_bond)
            if not nic_name:
                logger.error('Could not find interface with MAC {0}'.format(mac))
                return False

            nic['nic_name'] = nic_name
            logger.info('Mapped MAC {0} to interface {1} (bond={2})'.format(mac, nic_name, is_bond))

        return True

    if not update_nic_names():
        logger.info('NIC not found, performing PCI rescan and retrying...')
        _call_if_err_raise('echo 1 > /sys/bus/pci/rescan')
        if not update_nic_names():
            raise ConfigException('Failed to find network interfaces after PCI rescan')
    logger.info('NIC configuration: {0}'.format(nics))


