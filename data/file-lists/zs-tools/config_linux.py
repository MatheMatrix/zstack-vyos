def _call_if_err_raise(cmd):
    ret_code, stdout, stderr = shell.call(cmd)
    if ret_code != 0:
        raise ConfigException(stderr)
    return stdout


def _parse_nm_keyfile(content):
    """
    PARAM:
        INI NetworkManager keyfile content:
            # This file is auto generated by ZStack. Do not edit.
            [connection]
            id=zstack-ens3
            uuid=00758e09-706a-5c7b-bd38-e90be2a3730b
            type=ethernet
            interface-name=ens3
            autoconnect=true

            [ethernet]
            mac-address=fa:ef:c3:ae:1b:00
            mtu=1500

            [ipv4]
            method=manual
            address1=192.168.100.12/24,192.168.100.1
            gateway=192.168.100.1
            dns=223.5.5.5;
            route1=169.254.169.254/32,192.168.100.2

            [ipv6]
            method=disabled

    RETURN:
        JSON dict:
            {
                'connection': {
                    'id': 'zstack-ens3',
                    'uuid': '00758e09-706a-5c7b-bd38-e90be2a3730b',
                    'type': 'ethernet',
                    'interface-name': 'ens3',
                    'autoconnect': 'true'
                },
                'ethernet': {
                    'mac-address': 'fa:ef:c3:ae:1b:00',
                    'mtu': '1500'
                },
                'ipv4': {
                    'method': 'manual',
                    'address1': '192.168.100.12/24,192.168.100.1',
                    'gateway': '192.168.100.1',
                    'dns': '223.5.5.5;',
                    'route1': '169.254.169.254/32,192.168.100.2'
                },
                'ipv6': {
                    'method': 'disabled'
                }
            }
    """
    sections = {}
    current_section = None
    for raw_line in content.split('\n'):
        line = raw_line.strip()
        if not line or line.startswith('#'):
            continue
        if line.startswith('[') and line.endswith(']'):
            current_section = line[1:-1].strip()
            if current_section not in sections:
                sections[current_section] = {}
            continue
        if '=' in line and current_section:
            key, value = line.split('=', 1)
            sections[current_section][key.strip()] = value.strip()
    return sections


def _get_curr_port_list():
    curr_port_list = []
    port_info = _call_if_err_raise('ls /sys/class/net')
    if port_info:
        curr_port_list = [port for port in port_info.split('\n') if port != ""]
    return curr_port_list


