BOND_MODE_MAP = {
    'xor': 'balance-xor',
    'ab': 'active-backup',
}


def _normalize_bond_mode(mode):
    if not mode:
        return ''
    mode = str(mode).strip().lower()
    return BOND_MODE_MAP.get(mode, mode)


def _is_bond_nic(nic):
    mode = nic.get('bondMode')
    if mode is None:
        return False
    return _normalize_bond_mode(mode) != '' and _normalize_bond_mode(mode) != 'none'


def _bonding_option_string(nic):
    if not _is_bond_nic(nic):
        return ''
    normalized = _normalize_bond_mode(nic.get('bondMode'))
    if not normalized:
        return ''
    return 'mode={0} miimon=100'.format(normalized)


def _bond_slave_interfaces(nic):
    if not _is_bond_nic(nic):
        return []
    nic_name = nic.get('nic_name')
    if not nic_name:
        return []
    try:
        slaves = utils.find_bond_slaves(nic_name)
    except Exception:
        return []
    return [slave for slave in slaves if slave]

