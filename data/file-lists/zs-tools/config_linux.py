def _get_current_gateways_debian():
    """
    Parses /etc/network/interfaces on Debian-based systems to find gateway information.
    Returns a dictionary like: {'eth0': {4: '192.168.1.1', 6: 'fe80::1'}, ...}
    """
    current_gateways = {}
    interfaces_file = '/etc/network/interfaces'
    nic_name = None
    version = None # 4 for IPv4, 6 for IPv6
    try:
        if os.path.exists(interfaces_file):
            with open(interfaces_file, 'r') as f:
                for line in f:
                    line = line.strip()
                    if not line or line.startswith('#'):
                        continue
                    if line.startswith("iface"):
                        parts = line.split()
                        # Need at least 'iface <name> <family> <method>'
                        if len(parts) >= 4:
                            nic_name = parts[1]
                            address_family = parts[2]
                            version = 6 if address_family == 'inet6' else 4
                        else:
                            nic_name = None
                            version = None
                    elif line.lstrip().startswith("gateway") and nic_name is not None and version is not None:
                        parts = line.split()
                        if len(parts) >= 2:
                            gateway = parts[1]
                            if nic_name not in current_gateways:
                                current_gateways[nic_name] = {}
                            current_gateways[nic_name][version] = gateway
    except IOError as e: # More specific exception for file I/O
        logger.error("Failed to read {0}: {1}".format(interfaces_file, e))
    except Exception as e: # Catch other potential errors during parsing
        logger.error("Failed to parse gateway config from {0}: {1}".format(interfaces_file, e))
    if not current_gateways:
        logger.debug("No gateways found in {0} or parsing failed. Falling back to _get_current_gateways()".format(interfaces_file))
        return _get_current_gateways()
    return current_gateways

def _get_current_gateways():
    ip4_routes = _call_if_err_raise("ip -4 route show default").strip().split('\n')
    ip6_routes = _call_if_err_raise("ip -6 route show default").strip().split('\n')
    current_gateways = {}
    for route in ip4_routes + ip6_routes:
        if "default via" in route:
            parts = route.split()
            if "default" in parts and "via" in parts and "dev" in parts:
                gateway = parts[parts.index('via') + 1]
                nic_name = parts[parts.index('dev') + 1]
                version = 4 if '.' in gateway else 6
                current_gateways[nic_name] = current_gateways.get(nic_name, {})
                current_gateways[nic_name][version] = gateway
    return current_gateways

