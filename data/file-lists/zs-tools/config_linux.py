@utils.retry(times=3, sleep_time=5)
def _retry_find_expect_nics_by_mac(mac, ha_state, expected_name=None):
    """
    Find expected NICs by MAC address

    Args:
        mac: MAC address to search for
        ha_state: HA state (Enabled/Disconnecting/Reconnecting/Disabled)
        expected_name: Expected bond/nic name (optional, used in Reconnecting state to avoid multi-bond conflicts)
    """
    if not mac:
        raise ConfigException('mac is invalid')
    all_nics = utils.find_nic_list_by_mac(mac)
    physical_nics = []
    nic_dict = {}

    # Check if bond already exists for this MAC
    existing_bond = utils.find_bond_name_by_mac(mac)
    if existing_bond:
        nic_dict['bond'] = existing_bond
        logger.info('found existing bond device: %s for mac: %s' % (existing_bond, mac))

    for n in all_nics:
        if not utils.is_device_exists(n):
            raise ConfigException('could not find nic: %s, will retry again' % n)
        if utils.is_bond(n):
            if 'bond' not in nic_dict:
                nic_dict['bond'] = n
            continue
        # Skip bond slaves - EXCEPT during migration states where we need to reconfigure them
        master = utils.get_master_device(n)
        if master:
            if ha_state not in [netconfig.NET_CONFIG_HA_STATE_DISCONNECTING, netconfig.NET_CONFIG_HA_STATE_RECONECTING]:
                logger.info('nic %s is slave of %s, skip adding to physical_nics' % (n, master))
                continue
            else:
                logger.info('migration state: nic %s is slave of %s, keeping in physical_nics for bond reconfiguration' % (n, master))
        physical_nics.append(n)

    # For HA states, store all available physical NICs (including vnic)
    # They will be managed as bond slaves to keep bond alive during migration
    if ha_state == netconfig.NET_CONFIG_HA_STATE_ENABLED:
        # When bond exists and vnic appears, vnic should join bond as slave
        if 'bond' in nic_dict and len(physical_nics) >= 1:
            nic_dict['new_slaves'] = physical_nics
            logger.info('found new nics to add to bond: %s' % physical_nics)
        elif len(physical_nics) >= 2:
            # No bond yet, need at least 2 NICs to create bond
            for n in physical_nics:
                if utils.is_virtio_nic(n):
                    nic_dict['standby'] = n
                else:
                    nic_dict['master'] = n
        else:
            raise ConfigException('could not find enough physical nics for ha state: %s' % ha_state)
    elif ha_state in [netconfig.NET_CONFIG_HA_STATE_DISCONNECTING, netconfig.NET_CONFIG_HA_STATE_RECONECTING]:
        # During migration, all available physical NICs participate in bond
        nic_dict['available_nics'] = physical_nics
        logger.info('migration state %s, available nics: %s' % (ha_state, physical_nics))

        # In Reconnecting state, use expected_name to determine bond name
        # expected_name is either from management plane or PCI-based allocation
        if ha_state == netconfig.NET_CONFIG_HA_STATE_RECONECTING and 'bond' not in nic_dict:
            if expected_name:
                # Check if this bond exists (it might exist from previous config)
                if os.path.exists('/sys/class/net/{0}/bonding'.format(expected_name)):
                    nic_dict['bond'] = expected_name
                    logger.info('Reconnecting: found existing bond %s' % expected_name)
                else:
                    # Bond doesn't exist yet, but we'll create it with this name later
                    nic_dict['bond'] = expected_name
                    logger.info('Reconnecting: will create bond %s' % expected_name)
            else:
                # This should not happen in normal cases - expected_name should always be provided
                # Either from PCI-based allocation or management plane
                logger.error('Reconnecting: no expected_name provided for MAC %s' % mac)
                raise ConfigException('Reconnecting state requires expected_name for bond (MAC=%s)' % mac)
    else:
        if len(physical_nics) != 1:
            raise ConfigException('could not find enough physical nics for ha state: %s' % ha_state)
        nic_dict['master'] = physical_nics[0]

    logger.info('find nic list by mac[%s]: %s, nic_dict: %s' % (mac, all_nics, nic_dict))
    return nic_dict


def _config_nics_with_enable_ha(nics):
    if not nics:
        return
    logger.info('enable ha nics: %s' % nics)
    net_service = netconfig.get_system_network_service()
    service_type = net_service['type']
    service_config_path = net_service['path']

    # For Reconnecting state, determine NIC names by global PCI ordering
    # KISS principle: scan ALL system NICs, sort by PCI address = ethX order
    config_based_nic_names = {}
    ha_state = nics[0].get('haState') if nics else None

    if ha_state == netconfig.NET_CONFIG_HA_STATE_RECONECTING:
        logger.info('Reconnecting state: determining NIC names by global PCI ordering')

        for nic in nics:
            mac = nic.get('mac')

            # Use global PCI ordering to determine NIC name
            pci_based_name = utils.get_nic_name_by_global_pci_order(mac)
            if pci_based_name:
                config_based_nic_names[mac] = pci_based_name
                logger.info('Reconnecting: MAC %s -> %s (by global PCI order)' % (mac, pci_based_name))
            else:
                # Fallback: try to find existing bond with this MAC
                existing_bond = utils.find_bond_name_by_mac(mac)
                if existing_bond:
                    config_based_nic_names[mac] = existing_bond
                    logger.info('Reconnecting: MAC %s -> found existing bond %s' % (mac, existing_bond))
                else:
                    logger.warn('Reconnecting: MAC %s -> could not determine NIC name' % mac)

    # Configure each NIC
    for nic in nics:
        # Determine expected_name based on state
        mac = nic.get('mac')

        if mac in config_based_nic_names:
            # Use config-based name for Reconnecting state (from ifcfg-* or NetworkManager config)
            expected_name = config_based_nic_names[mac]
            logger.info('Using config-based name %s for MAC %s' % (expected_name, mac))
        else:
            # Use management plane provided name for other states
            expected_name = nic.get('nic_name') or nic.get('deviceName')

        nic_dict = _retry_find_expect_nics_by_mac(mac, nic.get('haState'), expected_name)
        if not nic_dict:
            raise ConfigException('could not find target nics by mac: {0}'.format(mac))

        bond_mode = nic.get('bondMode')
        bond_slaves = nic.get('bondSlaves') or []
        bond_slave_macs = nic.get('bondSlaveMacs') or []
        ha_state = nic.get('haState')

        # If bond exists in system, we should continue using bond mode even if bondMode is not provided
        # This happens during migration states (Enabled/Disconnecting/Reconnecting)
        detected_bond = 'bond' in nic_dict
        if detected_bond and not bond_mode:
            # Read bond mode from existing bond
            bond_sysfs_mode = '/sys/class/net/{0}/bonding/mode'.format(nic_dict['bond'])
            if os.path.exists(bond_sysfs_mode):
                with open(bond_sysfs_mode, 'r') as f:
                    # Format: "balance-xor 2" or "active-backup 1"
                    mode_str = f.read().strip().split()[0]
                    bond_mode = mode_str
                    logger.info('detected existing bond mode from sysfs: %s' % bond_mode)

        # Determine target device name and link type
        if detected_bond or bond_mode:
            # If bond exists, use existing bond name; otherwise use provided or master name
            if detected_bond:
                target_name = nic_dict['bond']
                logger.info('using existing bond device: %s' % target_name)

                # Get current bond slaves
                current_slaves = utils.find_bond_slaves(target_name) or []
                logger.info('current bond slaves: %s' % current_slaves)

                if ha_state == netconfig.NET_CONFIG_HA_STATE_ENABLED:
                    # Add new slaves (vnic) to existing bond slaves (VFs)
                    if 'new_slaves' in nic_dict:
                        bond_slaves = current_slaves + nic_dict['new_slaves']
                        logger.info('haState=Enabled: adding new slaves %s to bond, total slaves: %s' %
                                   (nic_dict['new_slaves'], bond_slaves))
                    elif not bond_slaves:
                        bond_slaves = current_slaves
                elif ha_state in [netconfig.NET_CONFIG_HA_STATE_DISCONNECTING, netconfig.NET_CONFIG_HA_STATE_RECONECTING]:
                    # Use available NICs as bond slaves during migration
                    if 'available_nics' in nic_dict:
                        # In Reconnecting state, rename new VF devices to match bond naming convention
                        # Use PCI address to identify devices reliably, not names
                        if ha_state == netconfig.NET_CONFIG_HA_STATE_RECONECTING:
                            # Build PCI-to-NIC mapping for stable identification
                            pci_nic_map = {}
                            vnic_list = []  # virtio NICs without PCI address

                            for nic_name in nic_dict['available_nics']:
                                pci_addr = utils.get_pci_address(nic_name)
                                if pci_addr:
                                    pci_nic_map[pci_addr] = nic_name
                                    logger.info('haState=Reconnecting: found VF %s at PCI %s' % (nic_name, pci_addr))
                                else:
                                    # virtio NIC or other non-PCI device
                                    vnic_list.append(nic_name)
                                    logger.info('haState=Reconnecting: found non-PCI device %s (likely vnic)' % nic_name)

                            # Sort by PCI address for stable ordering
                            sorted_pci_addrs = sorted(pci_nic_map.keys())

                            renamed_slaves = []

                            # Rename VF devices based on PCI address order
                            for idx, pci_addr in enumerate(sorted_pci_addrs):
                                current_name = pci_nic_map[pci_addr]
                                new_name = '{0}-phy{1}'.format(target_name, idx + 1)

                                # Skip renaming if already has the expected name
                                if current_name == new_name:
                                    renamed_slaves.append(current_name)
                                    logger.info('haState=Reconnecting: VF at PCI %s (%s) already has expected name' %
                                              (pci_addr, current_name))
                                    continue

                                try:
                                    logger.info('haState=Reconnecting: renaming VF at PCI %s from %s to %s' %
                                              (pci_addr, current_name, new_name))
                                    shell.run('ip link set dev {0} down'.format(current_name))
                                    shell.run('ip link set dev {0} name {1}'.format(current_name, new_name))
                                    shell.run('ip link set dev {0} up'.format(new_name))
                                    renamed_slaves.append(new_name)
                                except Exception as e:
                                    logger.warn('failed to rename %s (PCI %s) to %s: %s, using original name' %
                                              (current_name, pci_addr, new_name, str(e)))
                                    renamed_slaves.append(current_name)

                            # Add vnic devices (if any) to the end
                            renamed_slaves.extend(vnic_list)

                            bond_slaves = renamed_slaves
                            logger.info('haState=Reconnecting: final bond slaves (PCI-based): %s' % bond_slaves)
                        else:
                            bond_slaves = nic_dict['available_nics']
                            logger.info('haState=%s: using available nics as bond slaves: %s' % (ha_state, bond_slaves))
                    elif not bond_slaves:
                        bond_slaves = current_slaves
                else:
                    # Default: use current slaves if not provided
                    if not bond_slaves:
                        bond_slaves = current_slaves
            else:
                target_name = nic.get('nic_name') or nic.get('deviceName') or nic_dict.get('master')
                logger.info('creating new bond device: %s' % target_name)
                # Build bond_slaves list from nic_dict
                if not bond_slaves:
                    if 'master' in nic_dict:
                        bond_slaves.append(nic_dict['master'])
                    if 'standby' in nic_dict:
                        bond_slaves.append(nic_dict['standby'])
            link_type = netconfig.NET_CONFIG_BOND_TYPE
        else:
            # Non-bond mode
            if 'master' not in nic_dict:
                raise ConfigException('could not find master nic by mac: {0}'.format(nic.get('mac')))
            target_name = nic_dict['master']
            link_type = netconfig.NET_CONFIG_ETHER_TYPE

            # Delete old bond config if it exists
            if detected_bond:
                bond_name = nic_dict['bond']
                logger.info('deleting old bond config: %s' % bond_name)
                if service_config_path == netconfig.DEFAULT_CONFIG_PATH:
                    ifcfg_path = '{0}/ifcfg-{1}'.format(service_config_path, bond_name)
                    if os.path.exists(ifcfg_path):
                        os.remove(ifcfg_path)
                    if service_type == netconfig.NET_SERVICE_TYPE_NMCLI:
                        shell.run('nmcli c delete {0}'.format(bond_name))

        logger.info('configuring nic: target_name=%s, link_type=%s, bond_mode=%s, bond_slaves=%s' %
                   (target_name, link_type, bond_mode, bond_slaves))

        nic_config = netconfig.NetConfig(name=target_name,
                                         link_type=link_type,
                                         service_type=service_type,
                                         config_path=service_config_path,
                                         bond_mode=bond_mode,
                                         bond_slaves=bond_slaves,
                                         bond_slave_macs=bond_slave_macs)
        nic_config.mtu = nic.get('mtu')
        nic_config.mac = nic.get('mac')

        for ip in nic['vmIps']:
            if not ip.get('ip') or ip.get('ip').lower() == 'none':
                continue
            nic_config.add_ip_config(ip.get('ip'), ip.get('netmask'),
                                     version=ip.get('version'), gateway=ip.get('gateway') if ip.get('gateway') else None)
            if ip.get('dns') and nic.get('isDefault'):
                for dns in ip.get('dns'):
                    nic_config.add_dns_config(dns)
            if ip.get('routes'):
                for route in ip.get('routes'):
                    nic_config.add_route_config(route.get('prefix'), route.get('nexthop'), dev=None, version=ip.get('version'))

        nic_config.common_config_network(ha_state=nic.get('haState'))
        shell.run('ip addr show')
        shell.run('ip r show')


